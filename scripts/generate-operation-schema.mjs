#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { operationSchemaDocument } from "../src/shared/operation-schema.mjs";
import {
  BINARY_CLIPBOARD_MIME_ALLOWLIST,
  MAX_CLIPBOARD_BINARY_BYTES,
} from "../src/shared/peripheral-policy.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "extension", "operation-schema.generated.json");
const modulePath = join(root, "extension", "operation-schema.generated.js");
const policyModulePath = join(root, "extension", "peripheral-policy.generated.js");
const rendered = `${JSON.stringify(operationSchemaDocument(), null, 2)}\n`;
const capabilities = [...operationSchemaDocument().capabilities];
const authorizedTransactionMethods = [...operationSchemaDocument().authorizedTransactionMethods];
const operationDefinitions = operationSchemaDocument().methods;
const mutationMethods = operationDefinitions.filter(({ mutation }) => mutation).map(({ method }) => method);
const readOnlyMethods = operationDefinitions.filter(({ mutation }) => !mutation).map(({ method }) => method);
const profileGlobalMethods = operationDefinitions.filter(({ profileGlobal }) => profileGlobal).map(({ method }) => method);
const targetMethods = operationDefinitions.filter(({ targetScoped }) => targetScoped).map(({ method }) => method);
const capabilitiesDigest = createHash("sha256").update(JSON.stringify([...capabilities].sort()), "utf8").digest("hex");
const moduleRendered = `// Generated by scripts/generate-operation-schema.mjs; do not edit.\nexport const OPERATION_SCHEMA = ${JSON.stringify(operationSchemaDocument().schema)};\nexport const OPERATION_SCHEMA_VERSION = ${operationSchemaDocument().version};\nexport const OPERATION_SCHEMA_DIGEST = ${JSON.stringify(operationSchemaDocument().schemaDigest)};\nexport const ACTION_EVENT_CONTRACT = Object.freeze(${JSON.stringify(operationSchemaDocument().actionEvents)});\nexport const CAPABILITIES = Object.freeze(${JSON.stringify(capabilities)});\nexport const AUTHORIZED_TRANSACTION_METHODS = Object.freeze(${JSON.stringify(authorizedTransactionMethods)});\nexport const OPERATION_DEFINITIONS = Object.freeze(${JSON.stringify(operationDefinitions)});\nexport const MUTATION_METHODS = Object.freeze(${JSON.stringify(mutationMethods)});\nexport const READ_ONLY_METHODS = Object.freeze(${JSON.stringify(readOnlyMethods)});\nexport const PROFILE_GLOBAL_METHODS = Object.freeze(${JSON.stringify(profileGlobalMethods)});\nexport const TARGET_METHODS = Object.freeze(${JSON.stringify(targetMethods)});\nexport const CAPABILITIES_DIGEST = ${JSON.stringify(capabilitiesDigest)};\n`;
const policyModuleRendered = `// Generated by scripts/generate-operation-schema.mjs; do not edit.\nexport const MAX_CLIPBOARD_BINARY_BYTES = ${MAX_CLIPBOARD_BINARY_BYTES};\nexport const BINARY_CLIPBOARD_MIME_ALLOWLIST = Object.freeze(new Set(${JSON.stringify([...BINARY_CLIPBOARD_MIME_ALLOWLIST])}));\n`;

if (process.argv.includes("--check")) {
  let existing;
  let existingModule;
  let existingPolicyModule;
  try { existing = await readFile(outputPath, "utf8"); } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  try { existingModule = await readFile(modulePath, "utf8"); } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  try { existingPolicyModule = await readFile(policyModulePath, "utf8"); } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (existing !== rendered || existingModule !== moduleRendered || existingPolicyModule !== policyModuleRendered) {
    process.stderr.write(`Generated operation schema is stale: ${outputPath}\n`);
    process.exitCode = 1;
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true, mode: 0o755 });
  await writeFile(outputPath, rendered, { mode: 0o644 });
  await writeFile(modulePath, moduleRendered, { mode: 0o644 });
  await writeFile(policyModulePath, policyModuleRendered, { mode: 0o644 });
  process.stdout.write(`${outputPath}\n`);
}
